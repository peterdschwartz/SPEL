"""Move unit-test cases between machines: `spel archive pack|extract|list`.

`pack` writes one tar archive (`.tar.gz` by default; `.tar`, `.tar.xz` by the name) of one or
more cases with their reference data:

    spel-archive.json          the manifest: cases, what each holds, the E3SM checkout each was made from
    cases/<case>/...           unit-tests/<case>, without build and scratch directories (CLEAN)
    input-data/<case>/...      unit-tests/input-data/<case> (symlinks stored as the files they point to)
    proptest-data/<case>/...   unit-tests/proptest-data/<case>, with --proptest-data

Build and scratch directories (`build/`, `build-py*/`, the proptest scratch `proptest/`,
`__pycache__/`) are left out of the archive and, unless `--keep-builds`, deleted from the case:
they are regenerated by the next `spel run`/`spel proptest` on the other machine anyway.

`extract` puts each part back under a unit-tests directory (default: this machine's), refusing to
replace an existing case unless `--force`. The members are checked before anything is written:
an archive whose paths leave the destination, or that holds links or devices, is refused.
`--set-srcroot DIR` records the other machine's E3SM checkout in each case's `spel_meta.json`
(what `spel restore` patches); the pickled analysis (`fut.pkl`) stores paths relative to the
checkout and needs nothing.
"""

from __future__ import annotations

import fnmatch
import io
import json
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path, PurePosixPath
from typing import Iterable, Optional

from spel.scripts.config import CASE_META_FILENAME

MANIFEST = "spel-archive.json"
FORMAT = 1
# top-level entries of a case directory that are rebuilt, never archived
CLEAN = ("build", "build-py*", "proptest", "__pycache__")
PARTS = {"cases": "", "input-data": "input-data", "proptest-data": "proptest-data"}  # archive dir -> unit-tests subdir


class ArchiveError(Exception):
    pass


@dataclass
class CasePlan:
    name: str
    case_dir: Path
    input_dir: Optional[Path]
    proptest_dir: Optional[Path]
    clean: list[Path] = field(default_factory=list)  # build/scratch dirs of the case

    def size(self, path: Optional[Path]) -> int:
        return _size(path) if path is not None else 0


# -- pack


def plan_cases(names: Iterable[str], unittests: Path, proptest_data: bool) -> list[CasePlan]:
    plans = []
    for name in names:
        case_dir = unittests / name
        if not (case_dir / "fut.pkl").is_file() and not (case_dir / "CMakeLists.txt").is_file():
            raise ArchiveError(f"{case_dir}: not a unit-test case (no fut.pkl or CMakeLists.txt)")
        inp = unittests / "input-data" / name
        pt = unittests / "proptest-data" / name
        clean = sorted(p for p in case_dir.iterdir() if any(fnmatch.fnmatch(p.name, pat) for pat in CLEAN))
        plans.append(CasePlan(name, case_dir, inp if inp.is_dir() else None,
                              pt if proptest_data and pt.is_dir() else None, clean))
    return plans


def pack(names: list[str], output: Path, unittests: Path, *, proptest_data: bool = False,
         keep_builds: bool = False, dry_run: bool = False, yes: bool = False, out=sys.stdout) -> Optional[Path]:
    """Clean the cases (unless keep_builds) and write the archive. Returns its path (None on a dry run)."""
    if not names:
        raise ArchiveError("name at least one case")
    if len(set(names)) != len(names):
        raise ArchiveError("a case is named twice")
    plans = plan_cases(names, unittests, proptest_data)
    output = Path(output)
    mode = _write_mode(output)
    for p in plans:
        sizes = [f"case {_human(p.size(p.case_dir) - sum(_size(c) for c in p.clean))}",
                 f"input-data {_human(p.size(p.input_dir))}" if p.input_dir else "no input-data"]
        if p.proptest_dir:
            sizes.append(f"proptest-data {_human(p.size(p.proptest_dir))}")
        print(f"{p.name}: {', '.join(sizes)}", file=out)
        for c in p.clean:
            verb = "leave out" if keep_builds else "delete"
            print(f"  {verb} {c.relative_to(unittests)}/ ({_human(_size(c))})", file=out)
    if dry_run:
        print(f"(dry run: nothing written; the archive would be {output})", file=out)
        return None
    to_delete = [c for p in plans for c in p.clean] if not keep_builds else []
    if to_delete and not yes:
        if not sys.stdin.isatty():
            raise ArchiveError("deleting the build directories needs confirmation: pass -y, or --keep-builds")
        if input(f"Delete {len(to_delete)} build/scratch directories and write {output}? [y/N] ").strip().lower() != "y":
            print("cancelled", file=out)
            return None
    for c in to_delete:
        shutil.rmtree(c)
    manifest = _manifest(plans, unittests)
    output.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=output.name + ".", suffix=".part", dir=output.parent)
    os.close(fd)
    try:
        with tarfile.open(tmp, mode) as tar:
            data = json.dumps(manifest, indent=1).encode()
            info = tarfile.TarInfo(MANIFEST)
            info.size, info.mtime = len(data), int(datetime.now().timestamp())
            tar.addfile(info, io.BytesIO(data))
            for p in plans:
                _add_tree(tar, p.case_dir, f"cases/{p.name}", skip=set(p.clean))
                if p.input_dir:
                    _add_tree(tar, p.input_dir, f"input-data/{p.name}")
                if p.proptest_dir:
                    _add_tree(tar, p.proptest_dir, f"proptest-data/{p.name}")
        os.replace(tmp, output)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
    print(f"wrote {output} ({_human(output.stat().st_size)})", file=out)
    return output


def _add_tree(tar: tarfile.TarFile, root: Path, arcroot: str, skip: set[Path] = frozenset()) -> None:
    """Add a directory, symlinks stored as what they point to (the other machine lacks the targets)."""
    tar.add(root.resolve(), arcroot, recursive=False)
    for dirpath, dirnames, filenames in os.walk(root, followlinks=True):
        d = Path(dirpath)
        dirnames[:] = sorted(n for n in dirnames if d / n not in skip)
        for n in dirnames:
            tar.add((d / n).resolve(), f"{arcroot}/{(d / n).relative_to(root).as_posix()}", recursive=False)
        for n in sorted(filenames):
            src = d / n
            if src in skip:
                continue
            if not src.exists():  # a dangling symlink
                raise ArchiveError(f"{src}: broken symlink (to {os.readlink(src)})")
            real = src.resolve()
            tar.add(real, f"{arcroot}/{src.relative_to(root).as_posix()}", recursive=False)


def _manifest(plans: list[CasePlan], unittests: Path) -> dict:
    cases = {}
    for p in plans:
        meta = {}
        try:
            meta = json.loads((p.case_dir / CASE_META_FILENAME).read_text())
        except (OSError, ValueError):
            pass
        cases[p.name] = {
            "input_data": p.input_dir is not None, "proptest_data": p.proptest_dir is not None,
            "e3sm_srcroot": meta.get("e3sm_srcroot"), "created_at": meta.get("created_at"),
        }
    return {"format": FORMAT, "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "spel_commit": _git_head(), "cases": cases}


# -- extract and list


def read_manifest(archive: Path) -> dict:
    with tarfile.open(archive, "r:*") as tar:
        try:
            member = tar.getmember(MANIFEST)
        except KeyError:
            raise ArchiveError(f"{archive}: not a spel archive (no {MANIFEST})") from None
        f = tar.extractfile(member)
        assert f is not None
        manifest = json.loads(f.read())
    if manifest.get("format") != FORMAT:
        raise ArchiveError(f"{archive}: archive format {manifest.get('format')}, this SPEL reads {FORMAT}")
    return manifest


def list_archive(archive: Path, out=sys.stdout) -> dict:
    manifest = read_manifest(archive)
    sizes: dict[tuple[str, str], int] = {}
    with tarfile.open(archive, "r:*") as tar:
        for m in tar.getmembers():
            parts = PurePosixPath(m.name).parts
            if len(parts) >= 2 and m.isfile():
                sizes[(parts[0], parts[1])] = sizes.get((parts[0], parts[1]), 0) + m.size
    print(f"{archive}: written {manifest['created']} (SPEL {manifest.get('spel_commit') or '?'})", file=out)
    for name, info in manifest["cases"].items():
        label = {"cases": "case", "input-data": "input-data", "proptest-data": "proptest-data"}
        held = [f"{label[part]} {_human(sizes.get((part, name), 0))}" for part in PARTS if (part, name) in sizes]
        print(f"  {name}: {', '.join(held)}; made from {info.get('e3sm_srcroot') or '?'}", file=out)
    return manifest


def extract(archive: Path, unittests: Path, *, cases: Optional[list[str]] = None, force: bool = False,
            set_srcroot: Optional[Path] = None, out=sys.stdout) -> list[str]:
    """Extract the archive's cases (all, or `cases`) under `unittests`. Returns the case names."""
    manifest = read_manifest(archive)
    names = list(manifest["cases"])
    if cases:
        unknown = sorted(set(cases) - set(names))
        if unknown:
            raise ArchiveError(f"{archive} has no case {', '.join(unknown)} (it has {', '.join(names)})")
        names = [n for n in names if n in cases]
    unittests = Path(unittests)
    targets = {(part, n): unittests / sub / n if sub else unittests / n for part, sub in PARTS.items() for n in names}
    with tarfile.open(archive, "r:*") as tar:
        members = [m for m in tar.getmembers() if m.name != MANIFEST]
        chosen = []
        for m in members:
            parts = PurePosixPath(m.name).parts
            _check_member(m, parts)
            if (parts[0], parts[1]) in targets:
                chosen.append(m)
        present = sorted({(PurePosixPath(m.name).parts[0], PurePosixPath(m.name).parts[1]) for m in chosen})
        existing = [targets[k] for k in present if targets[k].exists()]
        if existing and not force:
            raise ArchiveError("these exist already (pass --force to replace them): "
                               + ", ".join(str(e) for e in existing))
        for e in existing:
            shutil.rmtree(e) if e.is_dir() and not e.is_symlink() else e.unlink()
        for m in chosen:
            parts = PurePosixPath(m.name).parts
            dest = targets[(parts[0], parts[1])].joinpath(*parts[2:])
            if m.isdir():
                dest.mkdir(parents=True, exist_ok=True)
                continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            src = tar.extractfile(m)
            assert src is not None
            with src, open(dest, "wb") as f:
                shutil.copyfileobj(src, f)
            os.chmod(dest, m.mode & 0o755 | 0o600)
            os.utime(dest, (m.mtime, m.mtime))
    for n in names:
        meta_path = unittests / n / CASE_META_FILENAME
        if set_srcroot is not None and meta_path.is_file():
            meta = json.loads(meta_path.read_text())
            meta["e3sm_srcroot_original"] = meta.get("e3sm_srcroot")
            meta["e3sm_srcroot"] = str(Path(set_srcroot).expanduser().resolve())
            meta_path.write_text(json.dumps(meta, indent=2) + "\n")
        info = manifest["cases"][n]
        made = info.get("e3sm_srcroot") or "?"
        note = f"; srcroot set to {set_srcroot}" if set_srcroot else f"; made from {made} (--set-srcroot to change)"
        print(f"{n} -> {unittests / n}{note}", file=out)
    return names


def _check_member(m: tarfile.TarInfo, parts: tuple[str, ...]) -> None:
    """Only plain files and directories under cases/, input-data/, proptest-data/<case>/."""
    bad = (not parts or PurePosixPath(m.name).is_absolute() or ".." in parts or parts[0] not in PARTS
           or len(parts) < 2 or not (m.isfile() or m.isdir()))
    if bad:
        raise ArchiveError(f"refusing archive member {m.name!r} ({'link' if m.issym() or m.islnk() else 'path'})")


# -- helpers


def _write_mode(output: Path) -> str:
    name = output.name
    if name.endswith((".tar.gz", ".tgz")):
        return "w:gz"
    if name.endswith((".tar.xz", ".txz")):
        return "w:xz"
    if name.endswith(".tar"):
        return "w"
    raise ArchiveError(f"{output}: name it .tar.gz, .tgz, .tar.xz or .tar")


def default_output(names: list[str]) -> Path:
    stem = names[0] if len(names) == 1 else f"{names[0]}+{len(names) - 1}"
    return Path(f"{stem}.spel.tar.gz")


def _size(path: Optional[Path]) -> int:
    if path is None or not path.exists():
        return 0
    if path.is_file():
        return path.stat().st_size
    total = 0
    for dirpath, _, filenames in os.walk(path, followlinks=True):
        for n in filenames:
            try:
                total += (Path(dirpath) / n).stat().st_size
            except OSError:
                pass
    return total


def _human(n: int) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024
    return f"{n:.1f} TB"


def _git_head() -> Optional[str]:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=Path(__file__).parent,
                              capture_output=True, text=True, check=True).stdout.strip() or None
    except (OSError, subprocess.CalledProcessError):
        return None
