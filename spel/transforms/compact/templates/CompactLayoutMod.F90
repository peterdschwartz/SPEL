module CompactLayoutMod
  !-----------------------------------------------------------------------
  ! !DESCRIPTION:
  ! Compact storage for subgrid fields that are only used on the soil
  ! filters (the per-step C/N/P flux fields of the ecosystem dynamics).
  !
  ! A compact field is allocated over the process's filter, 1:n with
  ! n = compact_num_soilp (patches) or compact_num_soilc (columns), never over
  ! begp:endp. The filters of the process's clumps are concatenated in clump
  ! order, so clump nc owns the contiguous slice
  ! compact_soilp_clump_off(nc)+1 : compact_soilp_clump_off(nc)+num_soilp(nc):
  ! the fp-th element of the clump's filter is element compact_soilp_off + fp,
  ! where compact_soilp_off is the thread-private offset set by
  ! compact_set_clump (called by get_clump_bounds).
  !
  ! Fields are stored in groups: one flat buffer data(1:n, 1:nfld) per group
  ! (field-major, so each field is a contiguous column), a group being the
  ! fields of one type component that are zeroed under the same condition at
  ! the same subgrid level. The types' pointer components alias the columns
  ! (this%x => compact_groups(id)%data(:, slot)), so process code is unchanged
  ! except for the index (compact_soilp_off + fp instead of filter(fp)).
  !
  ! The inverse maps compact_cidx_p(begp:endp) / compact_cidx_c(begc:endc)
  ! give, for every point, its compact index (> 0), -1 for an active point on
  ! a special landunit (the old full layout held the group's fill value
  ! there: the init-time zeroing of the special landunits) or 0 (the old
  ! layout held spval). History reads compact fields through them
  ! (histComputeMod, subgridAveViewMod).
  !
  ! When the dynamic subgrid changes the filters, compact_filters_set and
  ! compact_group_resize rebuild the maps and the buffers (nothing is
  ! preserved: every compact field is zeroed before it is read in a step) and
  ! the generated <type>_compact_bind routines re-point the components.
  !
  ! Only share modules may be used here: decompMod uses this module.
  ! The derived types that use this module and the routines that index their
  ! fields with the offsets are generated by `spel compact rewrite`.
  !
  ! !USES:
  use shr_kind_mod, only : r8 => shr_kind_r8
  use shr_sys_mod , only : shr_sys_abort  ! not endrun: decompMod uses this module
  !
  implicit none
  private
  !
  ! !PUBLIC DATA:
  real(r8), parameter, public :: compact_spval = 1.e36_r8   ! = elm_varcon's spval
  integer , parameter, public :: compact_lev_patch = 1, compact_lev_col = 2
  integer , parameter, public :: compact_max_groups = 256

  type, public :: compact_group_type
     character(len=64) :: name = ''
     integer  :: level = 0                 ! compact_lev_patch or compact_lev_col
     integer  :: nfld  = 0                 ! fields (columns of data)
     integer  :: n     = 0                 ! points of the filter at the last (re)allocation
     integer  :: nlev  = 0                 ! levels of a rank-2 group (0: rank-1 fields)
     real(r8) :: fill  = compact_spval     ! value of active special-landunit points (not stored)
     real(r8), pointer, contiguous :: data(:,:) => null()    ! rank-1 fields: (max(n,1), nfld)
     real(r8), pointer, contiguous :: data3(:,:,:) => null() ! rank-2 fields: (max(n,1), nlev, nfld)
  end type compact_group_type

  type(compact_group_type), public, target, save :: compact_groups(compact_max_groups)
  integer, public, save :: compact_ngroups = 0

  ! the process filters: counts, clump offsets (prefix counts), concatenations
  integer, public, save :: compact_num_soilp = 0, compact_num_soilc = 0
  integer, public, allocatable, save :: compact_soilp_clump_off(:), compact_soilc_clump_off(:)
  integer, public, allocatable, save :: compact_soilp_proc(:), compact_soilc_proc(:)
  ! inverse maps: > 0 compact index, -1 active special-landunit point, 0 other
  integer, public, allocatable, target, save :: compact_cidx_p(:), compact_cidx_c(:)
  ! the clump being computed: compact index of its first filter element minus one
  integer, public, save :: compact_soilp_off = 0, compact_soilc_off = 0
  !$omp threadprivate(compact_soilp_off, compact_soilc_off)
  ! the components point at the compact storage of the current filters
  logical, public, save :: compact_bound = .false.
  !$acc declare create(compact_groups, compact_cidx_p, compact_cidx_c, compact_num_soilp, compact_num_soilc)
  !
  ! !PUBLIC MEMBER FUNCTIONS:
  public :: compact_set_clump      ! thread-private offsets of a clump
  public :: compact_filters_set    ! the process filter of one level (counts, offsets, maps)
  public :: compact_group_new      ! a new group, allocated for the current filter
  public :: compact_group_resize   ! reallocate a group for the current filter
  public :: compact_group_fill     ! the group's value on active special-landunit points
  public :: compact_locate         ! (group, slot) of a pointer that aliases a compact field
  public :: compact_locate2        ! the same for a rank-2 pointer (a level block of a rank-2 group)
  public :: compact_report         ! the groups, for a log
  public :: compact_gather1        ! full-layout copy of a compact field (restart writes)
  public :: compact_gather2
  public :: compact_scatter1       ! members of a compact field from a full-layout array (restart reads)
  public :: compact_scatter2
  !-----------------------------------------------------------------------

contains

  !-----------------------------------------------------------------------
  subroutine compact_set_clump(nc)
    ! Select clump nc of the process (1:nclumps): its filter elements are
    ! compact_soilp_off+1 .. compact_soilp_off+num_soilp(nc).
    integer, intent(in) :: nc
    !-----------------------------------------------------------------------

    compact_soilp_off = 0
    compact_soilc_off = 0
    if (allocated(compact_soilp_clump_off)) then
       if (nc >= 1 .and. nc <= size(compact_soilp_clump_off)) compact_soilp_off = compact_soilp_clump_off(nc)
    end if
    if (allocated(compact_soilc_clump_off)) then
       if (nc >= 1 .and. nc <= size(compact_soilc_clump_off)) compact_soilc_off = compact_soilc_clump_off(nc)
    end if
  end subroutine compact_set_clump

  !-----------------------------------------------------------------------
  subroutine compact_filters_set(level, beg, end, num, idx, special)
    ! The process filter of one subgrid level, from the clumps' filters:
    ! num(nc) elements of clump nc, idx(:) their point indices concatenated in
    ! clump order (ascending over the process), special(beg:end) true for the
    ! points on special landunits. Builds the counts, the clump offsets and
    ! the inverse map.
    integer, intent(in) :: level            ! compact_lev_patch or compact_lev_col
    integer, intent(in) :: beg, end         ! process range of the level
    integer, intent(in) :: num(:)           ! filter elements per clump
    integer, intent(in) :: idx(:)           ! the filters, concatenated (size sum(num))
    logical, intent(in) :: special(beg:)    ! point lies on a special landunit
    !
    integer :: nc, k, p, n
    !-----------------------------------------------------------------------

    n = sum(num)
    if (size(idx) < n) call shr_sys_abort('CompactLayoutMod: compact_filters_set: idx shorter than sum(num)')
    do k = 2, n
       if (idx(k) <= idx(k-1)) call shr_sys_abort('CompactLayoutMod: compact_filters_set: filter not ascending')
    end do
    select case (level)
    case (compact_lev_patch)
       compact_num_soilp = n
       if (allocated(compact_soilp_clump_off)) deallocate(compact_soilp_clump_off, compact_soilp_proc)
       if (allocated(compact_cidx_p)) then
          !$acc exit data delete(compact_cidx_p)
          deallocate(compact_cidx_p)
       end if
       allocate(compact_soilp_clump_off(size(num)), compact_soilp_proc(max(n,1)), compact_cidx_p(beg:end))
       call build(compact_soilp_clump_off, compact_soilp_proc, compact_cidx_p)
       !$acc enter data copyin(compact_cidx_p)
       !$acc update device(compact_num_soilp)
    case (compact_lev_col)
       compact_num_soilc = n
       if (allocated(compact_soilc_clump_off)) deallocate(compact_soilc_clump_off, compact_soilc_proc)
       if (allocated(compact_cidx_c)) then
          !$acc exit data delete(compact_cidx_c)
          deallocate(compact_cidx_c)
       end if
       allocate(compact_soilc_clump_off(size(num)), compact_soilc_proc(max(n,1)), compact_cidx_c(beg:end))
       call build(compact_soilc_clump_off, compact_soilc_proc, compact_cidx_c)
       !$acc enter data copyin(compact_cidx_c)
       !$acc update device(compact_num_soilc)
    case default
       call shr_sys_abort('CompactLayoutMod: compact_filters_set: unknown level')
    end select
    compact_bound = .false.   ! the groups must be resized and the components rebound

  contains

    subroutine build(off, proc, cidx)
      integer, intent(out) :: off(:), proc(:), cidx(beg:)
      off(1) = 0
      do nc = 2, size(num)
         off(nc) = off(nc-1) + num(nc-1)
      end do
      do p = beg, end
         cidx(p) = merge(-1, 0, special(p))
      end do
      do k = 1, n
         p = idx(k)
         if (p < beg .or. p > end) call shr_sys_abort('CompactLayoutMod: compact_filters_set: filter index out of range')
         proc(k) = p
         cidx(p) = k
      end do
    end subroutine build

  end subroutine compact_filters_set

  !-----------------------------------------------------------------------
  integer function compact_group_new(name, level, nfld, nlev) result(id)
    ! A new group of nfld fields at `level`, allocated for the current filter
    ! and filled with spval. With nlev (> 0) the fields are rank 2 with levels
    ! 1:nlev (data3), else rank 1 (data).
    character(len=*), intent(in) :: name
    integer         , intent(in) :: level, nfld
    integer, optional, intent(in) :: nlev
    !-----------------------------------------------------------------------

    if (compact_ngroups >= compact_max_groups) call shr_sys_abort('CompactLayoutMod: too many compact groups')
    if (level /= compact_lev_patch .and. level /= compact_lev_col) then
       call shr_sys_abort('CompactLayoutMod: compact_group_new: unknown level for '//trim(name))
    end if
    compact_ngroups = compact_ngroups + 1
    id = compact_ngroups
    compact_groups(id)%name  = name
    compact_groups(id)%level = level
    compact_groups(id)%nfld  = nfld
    compact_groups(id)%nlev  = 0
    if (present(nlev)) compact_groups(id)%nlev = max(nlev, 0)
    compact_groups(id)%n     = -1
    call compact_group_resize(id)
  end function compact_group_new

  !-----------------------------------------------------------------------
  subroutine compact_group_resize(id)
    ! (Re)allocate group id for the current filter of its level and fill it
    ! with spval. Nothing is preserved: a compact field is zeroed before it
    ! is read in a step. The components that alias the group must be re-pointed
    ! afterwards (the generated <type>_compact_bind).
    integer, intent(in) :: id
    integer :: n
    !-----------------------------------------------------------------------

    if (id < 1 .or. id > compact_ngroups) call shr_sys_abort('CompactLayoutMod: compact_group_resize: no such group')
    associate(g => compact_groups(id))
    n = merge(compact_num_soilp, compact_num_soilc, g%level == compact_lev_patch)
    if (g%nlev > 0) then
       if (associated(g%data3)) then
          if (g%n == n) then
             g%data3(:,:,:) = compact_spval
             !$acc update device(g%data3)
             return
          end if
          !$acc exit data delete(g%data3)
          deallocate(g%data3)
       end if
       g%n = n
       allocate(g%data3(max(n,1), g%nlev, g%nfld))
       g%data3(:,:,:) = compact_spval
       !$acc enter data copyin(g%data3)
    else
       if (associated(g%data)) then
          if (g%n == n) then
             g%data(:,:) = compact_spval
             !$acc update device(g%data)
             return
          end if
          !$acc exit data delete(g%data)
          deallocate(g%data)
       end if
       g%n = n
       allocate(g%data(max(n,1), g%nfld))
       g%data(:,:) = compact_spval
       !$acc enter data copyin(g%data)
    end if
    end associate
  end subroutine compact_group_resize

  !-----------------------------------------------------------------------
  subroutine compact_group_fill(id, value)
    ! The value history reads on active special-landunit points of the group's
    ! fields (the init-time zeroing of the old full layout wrote it there).
    integer , intent(in) :: id
    real(r8), intent(in) :: value
    !-----------------------------------------------------------------------

    if (id < 1 .or. id > compact_ngroups) call shr_sys_abort('CompactLayoutMod: compact_group_fill: no such group')
    compact_groups(id)%fill = value
    !$acc update device(compact_groups(id)%fill)
  end subroutine compact_group_fill

  !-----------------------------------------------------------------------
  subroutine compact_locate(ptr, group, slot, lev)
    ! The (group, slot) whose column `ptr` aliases, or (0, 0). With `lev`, also
    ! a level slice `data3(:, lev, slot)` of a rank-2 group (a per-level
    ! history registration of a rank-2 field); lev = 0 for a rank-1 group.
    real(r8), pointer, intent(in) :: ptr(:)
    integer, intent(out) :: group, slot
    integer, intent(out), optional :: lev
    integer :: g, s, l
    !-----------------------------------------------------------------------

    group = 0
    slot = 0
    if (present(lev)) lev = 0
    if (.not. associated(ptr)) return
    do g = 1, compact_ngroups
       if (compact_groups(g)%nlev == 0) then
          if (.not. associated(compact_groups(g)%data)) cycle
          if (size(ptr) /= size(compact_groups(g)%data, 1)) cycle
          do s = 1, compact_groups(g)%nfld
             if (associated(ptr, compact_groups(g)%data(:, s))) then
                group = g
                slot = s
                return
             end if
          end do
       else if (present(lev)) then
          if (.not. associated(compact_groups(g)%data3)) cycle
          if (size(ptr) /= size(compact_groups(g)%data3, 1)) cycle
          do s = 1, compact_groups(g)%nfld
             do l = 1, compact_groups(g)%nlev
                if (associated(ptr, compact_groups(g)%data3(:, l, s))) then
                   group = g
                   slot = s
                   lev = l
                   return
                end if
             end do
          end do
       end if
    end do
  end subroutine compact_locate

  !-----------------------------------------------------------------------
  subroutine compact_locate2(ptr, group, slot)
    ! The (group, slot) whose level block `ptr` aliases (a rank-2 field), or (0, 0).
    real(r8), pointer, intent(in) :: ptr(:,:)
    integer, intent(out) :: group, slot
    integer :: g, s
    !-----------------------------------------------------------------------

    group = 0
    slot = 0
    if (.not. associated(ptr)) return
    do g = 1, compact_ngroups
       if (compact_groups(g)%nlev == 0 .or. .not. associated(compact_groups(g)%data3)) cycle
       if (size(ptr, 1) /= size(compact_groups(g)%data3, 1) .or. size(ptr, 2) /= compact_groups(g)%nlev) cycle
       do s = 1, compact_groups(g)%nfld
          if (associated(ptr, compact_groups(g)%data3(:, :, s))) then
             group = g
             slot = s
             return
          end if
       end do
    end do
  end subroutine compact_locate2

  !-----------------------------------------------------------------------
  subroutine compact_gather1(ptr, full)
    ! The full-layout copy of a rank-1 compact field over its level's process
    ! range: members from the field, active special-landunit points the
    ! group's fill, others spval (what the old array held). For restart writes.
    real(r8), pointer, intent(in) :: ptr(:)
    real(r8), pointer, intent(out) :: full(:)   ! allocated here (a pointer: restartvar's data dummy is one)
    integer :: g, s, p, k
    !-----------------------------------------------------------------------

    call compact_locate(ptr, g, s)
    if (g == 0) call shr_sys_abort('CompactLayoutMod: compact_gather1: not a compact field')
    if (compact_groups(g)%level == compact_lev_patch) then
       allocate(full(lbound(compact_cidx_p, 1):ubound(compact_cidx_p, 1)))
       do p = lbound(full, 1), ubound(full, 1)
          k = compact_cidx_p(p)
          full(p) = merge(compact_groups(g)%fill, compact_spval, k < 0)
          if (k > 0) full(p) = ptr(k)
       end do
    else
       allocate(full(lbound(compact_cidx_c, 1):ubound(compact_cidx_c, 1)))
       do p = lbound(full, 1), ubound(full, 1)
          k = compact_cidx_c(p)
          full(p) = merge(compact_groups(g)%fill, compact_spval, k < 0)
          if (k > 0) full(p) = ptr(k)
       end do
    end if
  end subroutine compact_gather1

  !-----------------------------------------------------------------------
  subroutine compact_gather2(ptr, full)
    ! compact_gather1 for a rank-2 compact field (full(point, level)).
    real(r8), pointer, intent(in) :: ptr(:,:)
    real(r8), pointer, intent(out) :: full(:,:)   ! allocated here
    integer :: g, s, p, k
    !-----------------------------------------------------------------------

    call compact_locate2(ptr, g, s)
    if (g == 0) call shr_sys_abort('CompactLayoutMod: compact_gather2: not a compact field')
    if (compact_groups(g)%level == compact_lev_patch) then
       allocate(full(lbound(compact_cidx_p, 1):ubound(compact_cidx_p, 1), size(ptr, 2)))
       do p = lbound(full, 1), ubound(full, 1)
          k = compact_cidx_p(p)
          full(p, :) = merge(compact_groups(g)%fill, compact_spval, k < 0)
          if (k > 0) full(p, :) = ptr(k, :)
       end do
    else
       allocate(full(lbound(compact_cidx_c, 1):ubound(compact_cidx_c, 1), size(ptr, 2)))
       do p = lbound(full, 1), ubound(full, 1)
          k = compact_cidx_c(p)
          full(p, :) = merge(compact_groups(g)%fill, compact_spval, k < 0)
          if (k > 0) full(p, :) = ptr(k, :)
       end do
    end if
  end subroutine compact_gather2

  !-----------------------------------------------------------------------
  subroutine compact_scatter1(full, ptr)
    ! The members of a rank-1 compact field from a full-layout array (restart reads).
    real(r8), intent(in) :: full(:)
    real(r8), pointer, intent(inout) :: ptr(:)
    integer :: g, s, p, k
    !-----------------------------------------------------------------------

    call compact_locate(ptr, g, s)
    if (g == 0) call shr_sys_abort('CompactLayoutMod: compact_scatter1: not a compact field')
    if (compact_groups(g)%level == compact_lev_patch) then
       do p = lbound(compact_cidx_p, 1), ubound(compact_cidx_p, 1)
          k = compact_cidx_p(p)
          if (k > 0) ptr(k) = full(p - lbound(compact_cidx_p, 1) + 1)
       end do
    else
       do p = lbound(compact_cidx_c, 1), ubound(compact_cidx_c, 1)
          k = compact_cidx_c(p)
          if (k > 0) ptr(k) = full(p - lbound(compact_cidx_c, 1) + 1)
       end do
    end if
  end subroutine compact_scatter1

  !-----------------------------------------------------------------------
  subroutine compact_scatter2(full, ptr)
    ! compact_scatter1 for a rank-2 compact field.
    real(r8), intent(in) :: full(:,:)
    real(r8), pointer, intent(inout) :: ptr(:,:)
    integer :: g, s, p, k
    !-----------------------------------------------------------------------

    call compact_locate2(ptr, g, s)
    if (g == 0) call shr_sys_abort('CompactLayoutMod: compact_scatter2: not a compact field')
    if (compact_groups(g)%level == compact_lev_patch) then
       do p = lbound(compact_cidx_p, 1), ubound(compact_cidx_p, 1)
          k = compact_cidx_p(p)
          if (k > 0) ptr(k, :) = full(p - lbound(compact_cidx_p, 1) + 1, :)
       end do
    else
       do p = lbound(compact_cidx_c, 1), ubound(compact_cidx_c, 1)
          k = compact_cidx_c(p)
          if (k > 0) ptr(k, :) = full(p - lbound(compact_cidx_c, 1) + 1, :)
       end do
    end if
  end subroutine compact_scatter2

  !-----------------------------------------------------------------------
  subroutine compact_report(unit)
    ! One line per group.
    integer, intent(in) :: unit
    integer :: g
    !-----------------------------------------------------------------------

    write(unit, '(a,i0,a,i0,a,i0,a)') 'compact layout: ', compact_ngroups, ' groups, filters: ', &
         compact_num_soilp, ' patches, ', compact_num_soilc, ' columns'
    do g = 1, compact_ngroups
       associate(grp => compact_groups(g))
       write(unit, '(a,i0,a,a,a,i0,a,i0,a,i0,a,es9.2)') '  group ', g, ' ', trim(grp%name), ': ', grp%nfld, &
            ' fields x ', grp%n, ' points x ', max(grp%nlev, 1), ' levels, fill ', grp%fill
       end associate
    end do
  end subroutine compact_report

end module CompactLayoutMod
