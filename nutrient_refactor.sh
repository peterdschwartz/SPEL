#!/bin/bash
# Apply the nutrient base-type refactor to an E3SM checkout, then split the data-type
# modules and prune unused members: one commit per step.
#
#   nutrient_refactor.sh [-s SRCROOT] [-f FIRST_STEP] [-n]
#
#   -s SRCROOT     E3SM checkout (default: ~/climate-projects/E3SM)
#   -f FIRST_STEP  start at this step number (resume after a failure; default 1)
#   -n             list the steps and exit
#
# Before each step the checkout is reanalyzed (`spel analyze`): every step reads
# the sources the previous one wrote. Each step's changes under components/elm/src
# are committed with the SPEL commit that made them.
#
# Prerequisites:
#   * `spel` on PATH (e.g. source ~/climate-projects/py12env/bin/activate)
#   * the unused legacy C/N/P type modules removed (CNCarbonStateType.F90 & co.;
#     commit fc7c467c8c "Remove unused legacy C/N/P types" on
#     peterdschwartz/lnd/nutrient-base-types, cherry-pick it onto other branches)
#   * no uncommitted changes to tracked files (the script refuses otherwise)
set -euo pipefail

SRCROOT=~/climate-projects/E3SM
FIRST=1
LIST=0
while getopts "s:f:nh" opt; do
  case $opt in
    s) SRCROOT=$OPTARG ;;
    f) FIRST=$OPTARG ;;
    n) LIST=1 ;;
    *) sed -n '2,20p' "$0"; exit 1 ;;
  esac
done

SPEL_ROOT=$(cd "$(dirname "$0")" && pwd)

# step command | commit subject
STEPS=(
  "spel transform nutrient-extract|Extract common nutrient base types as a \`core\` component (spel transform nutrient-extract)"
  "spel transform nutrient-species|Give each nutrient core its species (spel transform nutrient-species)"
  "spel transform nutrient-merge|Merge shared SetValues/ZeroDWT code into core-component routines"
  "spel transform nutrient-groups|Group the N/P-only fields into role components (spel transform nutrient-groups)"
  "spel transform nutrient-merge --procedure init|Merge the shared allocations of the nutrient Init routines into the cores"
  "spel transform nutrient-history|One history registration per nutrient core field (spel transform nutrient-history)"
  "spel transform nutrient-restart|One restartvar per nutrient core field (spel transform nutrient-restart)"
  "spel transform nutrient-merge --procedure summary|Merge shared Summary code into core-component routines"
  "spel transform split|Split Vegetation/Column/GridcellDataType into type modules (spel transform split)"
  "spel prune|Delete derived-type members nothing accesses (spel prune)"
)

if [ "$LIST" = 1 ]; then
  for i in "${!STEPS[@]}"; do echo "$((i + 1)). ${STEPS[$i]%%|*}"; done
  exit 0
fi

command -v spel > /dev/null || { echo "spel not on PATH (activate its environment)"; exit 1; }
git -C "$SRCROOT" rev-parse --git-dir > /dev/null 2>&1 || { echo "$SRCROOT: not a git checkout"; exit 1; }
if [ "$FIRST" = 1 ] && [ -e "$SRCROOT/components/elm/src/biogeochem/CNCarbonStateType.F90" ]; then
  echo "$SRCROOT still has the legacy C/N/P types (CNCarbonStateType.F90 & co.)."
  echo "Cherry-pick fc7c467c8c (Remove unused legacy C/N/P types) first."
  exit 1
fi
if ! git -C "$SRCROOT" diff --quiet || ! git -C "$SRCROOT" diff --cached --quiet; then
  echo "$SRCROOT has uncommitted changes to tracked files; commit or stash them first:"
  git -C "$SRCROOT" status --short --untracked-files=no
  exit 1
fi

SPEL_HASH=$(git -C "$SPEL_ROOT" rev-parse --short=7 HEAD)
if ! git -C "$SPEL_ROOT" diff --quiet HEAD -- spel; then
  echo "warning: SPEL has uncommitted changes; commits will cite $SPEL_HASH"
fi
LOGS=$(mktemp -d -t nutrient-refactor.XXXX)
echo "E3SM: $SRCROOT ($(git -C "$SRCROOT" rev-parse --abbrev-ref HEAD) @ $(git -C "$SRCROOT" rev-parse --short HEAD))"
echo "SPEL: $SPEL_HASH; logs in $LOGS"

for i in "${!STEPS[@]}"; do
  n=$((i + 1))
  [ "$n" -lt "$FIRST" ] && continue
  cmd=${STEPS[$i]%%|*}
  subject=${STEPS[$i]#*|}
  echo "== $n. $cmd"
  spel analyze --srcroot "$SRCROOT" > "$LOGS/$n-analyze.log" 2>&1 \
    || { echo "analyze failed: $LOGS/$n-analyze.log"; exit 1; }
  $cmd --srcroot "$SRCROOT" > "$LOGS/$n-step.log" 2>&1 \
    || { echo "step failed: $LOGS/$n-step.log"; tail -5 "$LOGS/$n-step.log"; echo "resume with -f $n"; exit 1; }
  # what the step reports (merged families, refusals), without the log noise
  grep -v "INFO\|wrote " "$LOGS/$n-step.log" | sed 's/\x1b\[[0-9;]*m//g' | grep -v '^\s*$' || true
  git -C "$SRCROOT" add -A components/elm/src
  if git -C "$SRCROOT" diff --cached --quiet; then
    echo "step $n changed nothing; stopping (resume with -f $((n + 1)) if that is expected)"
    exit 1
  fi
  git -C "$SRCROOT" commit -q -m "$subject" -m "Generated by \`$cmd\` (SPEL $SPEL_HASH), after \`spel analyze\`."
  echo "   committed $(git -C "$SRCROOT" rev-parse --short HEAD)"
done
echo "done. Verify (bit-for-bit vs the starting commit), then \`spel analyze --srcroot $SRCROOT\`."
